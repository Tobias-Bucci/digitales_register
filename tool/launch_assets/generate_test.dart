// Regenerates the native splash assets from the launch animation's geometry
// and colours, so the native splash and the first Flutter frame match:
//
//   flutter test tool/launch_assets/generate_test.dart
//
// It lives outside test/ so the normal test run does not rewrite files.

import 'dart:io';
import 'dart:ui' as ui;

import 'package:dr/ui/launch/launch_logo_painter.dart';
import 'package:dr/ui/launch/launch_tokens.dart';
import 'package:flutter/painting.dart';
import 'package:flutter_test/flutter_test.dart';

typedef _G = LaunchLogoGeometry;

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('writes Android vector drawables and colours', () {
    for (final (directory, palette) in [
      ('android/app/src/main/res/drawable', LaunchPalette.light),
      ('android/app/src/main/res/drawable-night', LaunchPalette.dark),
    ]) {
      File('$directory/launch_logo.xml')
          .writeAsStringSync(_vectorDrawable(palette));
      File('$directory/launch_logo_splash_icon.xml').writeAsStringSync(
          _vectorDrawable(palette, extent: LaunchLayout.androidSplashIcon));
    }
    _setAndroidColor('android/app/src/main/res/values/colors.xml',
        LaunchPalette.light.background);
    _setAndroidColor('android/app/src/main/res/values-night/colors.xml',
        LaunchPalette.dark.background);
  });

  test('writes iOS launch images', () async {
    const images = 'ios/Runner/Assets.xcassets/LaunchImage.imageset';
    const backgrounds = 'ios/Runner/Assets.xcassets/LaunchBackground.imageset';
    for (final scale in [1, 2, 3]) {
      final suffix = scale == 1 ? '' : '@${scale}x';
      for (final (name, palette) in [
        ('LaunchImage', LaunchPalette.light),
        ('LaunchImageDark', LaunchPalette.dark),
      ]) {
        await _writePng(
            '$images/$name$suffix.png', LaunchLayout.mobileExtent * scale,
            (canvas, extent) {
          LaunchLogoPainter(
            frame: StaticLaunchFrame(),
            palette: palette,
            logoExtent: extent,
            paintBackground: false,
          ).paint(canvas, Size.square(extent));
        });
      }
    }
    for (final (name, palette) in [
      ('background', LaunchPalette.light),
      ('darkbackground', LaunchPalette.dark),
    ]) {
      await _writePng('$backgrounds/$name.png', 1, (canvas, extent) {
        canvas.drawRect(Rect.fromLTWH(0, 0, extent, extent),
            Paint()..color = palette.background);
      });
    }
  });
}

String _hex(Color color) =>
    '#${color.toARGB32().toRadixString(16).padLeft(8, '0').substring(2).toUpperCase()}';

String _n(double value) =>
    value == value.roundToDouble() ? '${value.toInt()}' : '$value';

String _roundedRect(Rect rect, double radius) {
  final r = _n(radius);
  return 'M${_n(rect.left + radius)},${_n(rect.top)} '
      'H${_n(rect.right - radius)} A$r,$r 0 0 1 ${_n(rect.right)},${_n(rect.top + radius)} '
      'V${_n(rect.bottom - radius)} A$r,$r 0 0 1 ${_n(rect.right - radius)},${_n(rect.bottom)} '
      'H${_n(rect.left + radius)} A$r,$r 0 0 1 ${_n(rect.left)},${_n(rect.bottom - radius)} '
      'V${_n(rect.top + radius)} A$r,$r 0 0 1 ${_n(rect.left + radius)},${_n(rect.top)} Z';
}

/// The logo as a vector drawable of [extent] dp; anything beyond
/// [LaunchLayout.mobileExtent] becomes transparent padding around it.
///
/// Padding is part of the viewport rather than an InsetDrawable: Android 12+
/// scales the splash icon to a fixed size, and dp insets do not scale with it.
String _vectorDrawable(LaunchPalette palette,
    {double extent = LaunchLayout.mobileExtent}) {
  final size = _n(extent);
  final viewport = _G.canvas * extent / LaunchLayout.mobileExtent;
  final canvas = _n(viewport);
  final padding = (viewport - _G.canvas) / 2;
  const indent = '    ';
  final buffer = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- Generated by tool/launch_assets/generate_test.dart from '
        'lib/ui/launch/launch_tokens.dart. Do not edit. -->')
    ..writeln(
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"')
    ..writeln('    android:width="${size}dp"')
    ..writeln('    android:height="${size}dp"')
    ..writeln('    android:viewportWidth="$canvas"')
    ..writeln('    android:viewportHeight="$canvas">')
    ..writeln('$indent<group android:translateX="${_n(padding)}" '
        'android:translateY="${_n(padding)}">')
    ..writeln('    <path')
    ..writeln('        android:fillColor="${_hex(palette.fill)}"')
    ..writeln('        android:strokeColor="${_hex(palette.outline)}"')
    ..writeln('        android:strokeWidth="${_n(_G.outlineWidth)}"')
    ..writeln(
        '        android:pathData="${_roundedRect(_G.outline, _G.outlineRadius)}" />');
  for (final top in _G.ringTops) {
    final ring = Rect.fromLTWH(_G.ringLeft, top, _G.ringWidth, _G.ringHeight);
    buffer
      ..writeln('    <path')
      ..writeln('        android:fillColor="${_hex(palette.green)}"')
      ..writeln(
          '        android:pathData="${_roundedRect(ring, _G.ringRadius)}" />');
  }
  for (var i = 0; i < _G.lineYs.length; i++) {
    buffer
      ..writeln('    <path')
      ..writeln('        android:strokeColor="${_hex(palette.lines)}"')
      ..writeln('        android:strokeWidth="${_n(_G.lineWidth)}"')
      ..writeln('        android:strokeLineCap="round"')
      ..writeln(
          '        android:pathData="M${_n(_G.lineStart)},${_n(_G.lineYs[i])} '
          'H${_n(_G.lineEnds[i])}" />');
  }
  buffer
    ..writeln('    <path')
    ..writeln('        android:strokeColor="${_hex(palette.green)}"')
    ..writeln('        android:strokeWidth="${_n(_G.checkWidth)}"')
    ..writeln('        android:strokeLineCap="round"')
    ..writeln('        android:strokeLineJoin="round"')
    ..writeln(
        '        android:pathData="M${_n(_G.checkStart.dx)},${_n(_G.checkStart.dy)} '
        'L${_n(_G.checkCorner.dx)},${_n(_G.checkCorner.dy)} '
        'L${_n(_G.checkTip.dx)},${_n(_G.checkTip.dy)}" />')
    ..writeln('$indent</group>')
    ..writeln('</vector>');
  return buffer.toString();
}

void _setAndroidColor(String path, Color color) {
  final file = File(path);
  final updated = file.readAsStringSync().replaceFirst(
      RegExp('<color name="splash_color">#[0-9A-Fa-f]+</color>'),
      '<color name="splash_color">${_hex(color)}</color>');
  file.writeAsStringSync(updated);
}

Future<void> _writePng(String path, double extent,
    void Function(Canvas canvas, double extent) draw) async {
  final recorder = ui.PictureRecorder();
  draw(Canvas(recorder), extent);
  final image =
      await recorder.endRecording().toImage(extent.round(), extent.round());
  final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
  File(path).writeAsBytesSync(bytes!.buffer.asUint8List());
}
